/**
 * 界面文案：全部**悬浮提示**（鼠标悬停时出现的说明）的唯一来源。
 *
 * ## 这个文件是干什么的
 *
 * 用户 2026-10 的要求：
 *
 * > 告诉我 UI 界面所有的悬浮提示在程序的哪里可以设置，我要自己编辑对应的提示内容。
 *
 * 因此界面上所有"悬停才出现"的文字都搬到了这里——`Tooltip` 组件的 `text`、
 * 以及原生 `title` 属性。以后想改哪句提示，改这个文件里的对应条目即可。
 *
 * ## 语言风格（用户 2026-10 的三次要求，最近一次是"再精简一遍"）
 *
 * > 我要修改所有悬浮显示的信息，调整语言风格，不要太口语化，要精简，
 * > 但是保持表意的准确性。
 *
 * > 再次整理、精简界面及悬浮的文字，要求简洁清晰，不要长篇大论，
 * > 不要使用口语化表达，使用书面语准确表达。
 *
 * 因此这里的文字一律**书面语、短句、能删就删**：
 *
 * - 不用"点一下""按住这里""想……就……""用得上""可以"这类口语与赘词；
 * - 一条只说一件事，**尽量一句**；确需两三条时按"是什么 / 约束 / 后果"排序；
 * - 但**约束与后果必须留着**（区间开闭、单位、会不会覆盖、删掉能不能恢复、
 *   会不会还原壁纸）——精简的是措辞，不是信息；
 * - 不用 Markdown 记号：提示框是纯文本渲染的，写 `**回收站**` 会原样显示星号；
 * - 句末统一用句号（列表项与字段名除外）。
 *
 * 改文案时请沿用这个风格。
 *
 * ## 怎么改（重要）
 *
 * 1. 找到想改的那一条（每条上面都有一句"它显示在哪里"的注释）；
 * 2. 改引号里的文字。要换行就写 `\n`，或者用反引号包起多行（见下面几处例子）；
 * 3. **必须重新构建程序**（`pwsh -File scripts\build-package.ps1`）才会生效：
 *    这些文字是在**编译期**被前端打包进 exe 的，程序运行时不读任何配置文件。
 *
 * ## 带参数的那几条是什么
 *
 * 少数提示里要嵌运行时才知道的东西（显示器真实名字、图库路径、数量），
 * 因此它们是**函数**：调用时把值传进去。函数体里的文字照样可以直接改，
 * 但 `${...}` 那部分不要动（那是插值）。
 *
 * ## 什么不该放进来
 *
 * 界面上的常驻文字（标题、按钮上的字、字段名）不在这里——它们不是"悬浮提示"，
 * 而且参与布局（改了可能让某一行折行）。这里只放悬停才出现的说明。
 */

